// API URL and Google client id compiled into the app: environment variables win over this machine's
// local.properties (e.g. the local server for the IDE's Run and Debug, LOCAL_DEVELOPMENT.md), which wins over
// gradle.properties. A blank variable counts as missing: CI sets an empty one for an unset repository variable.
val localProperties = providers.fileContents(rootProject.layout.projectDirectory.file("local.properties")).asText
    .map { text -> Properties().apply { load(text.reader()) } }

fun setting(env: String, property: String) = providers.environmentVariable(env).filter { it.isNotBlank() }
    .orElse(localProperties.map { it.getProperty(property).orEmpty() }.filter { it.isNotBlank() })
    .orElse(providers.gradleProperty(property))

/** A Chrome or Chromium for the wasm browser tests, or null if this machine has none. */
fun headlessChrome(): String? {
    providers.environmentVariable("CHROME_BIN").orNull?.takeIf { it.isNotBlank() }?.let { return it }
    val onPath = providers.environmentVariable("PATH").orNull.orEmpty().split(File.pathSeparator)
        .flatMap { dir -> listOf("google-chrome", "google-chrome-stable", "chromium", "chromium-browser").map { File(dir, it) } }
    val playwright = File(System.getProperty("user.home"), ".cache/ms-playwright").listFiles().orEmpty()
        .filter { it.name.startsWith("chromium-") }.sortedDescending().map { File(it, "chrome-linux64/chrome") }
    return (onPath + playwright).firstOrNull { it.canExecute() }?.path
}

// The end-to-end tests (`-Pe2e`, LOCAL_DEVELOPMENT.md): the browser tests against a local server started for the run.
// The whole build then compiles for that server with development sign-in, as a local-dev build does.
val e2e = providers.gradleProperty("e2e").isPresent
val e2ePort = 8787
val e2eApiUrl = "http://localhost:$e2ePort"

val generateAppConfig = tasks.register("generateAppConfig") {
    val apiUrl = if (e2e) provider { e2eApiUrl } else setting("KAPELUSZ_API_URL", "kapelusz.apiUrl")
    val webClientId = setting("KAPELUSZ_GOOGLE_WEB_CLIENT_ID", "kapelusz.googleWebClientId")
    val webUrl = setting("KAPELUSZ_WEB_URL", "kapelusz.webUrl")
    // Sign-in as a made-up user, for the local server (LOCAL_DEVELOPMENT.md); never set for a release.
    val devSignIn = if (e2e) provider { true } else setting("KAPELUSZ_DEV_SIGN_IN", "kapelusz.devSignIn").orElse("false").map { it.toBoolean() }
    // Without a key (local builds, unless set) there is no map to pick a place on.
    val mapsKey = setting("KAPELUSZ_GOOGLE_MAPS_ANDROID_KEY", "kapelusz.googleMapsAndroidKey").orElse("")
    val versionName = providers.gradleProperty("kapelusz.versionName")
    // CI passes an increasing number (its run number + 10); local builds are "dev".
    val versionCode = providers.environmentVariable("KAPELUSZ_VERSION_CODE").orElse("0")
    inputs.property("versionName", versionName)
    inputs.property("versionCode", versionCode)
    inputs.property("apiUrl", apiUrl)
    inputs.property("webUrl", webUrl)
    inputs.property("webClientId", webClientId)
    inputs.property("devSignIn", devSignIn)
    // What scripts/deploy.sh builds (and any other release): asked for by name, so known before the build runs.
    val release = gradle.startParameter.taskNames.any { it.contains("Release") || it.endsWith("wasmJsBrowserDistribution") }
    inputs.property("release", release)
    inputs.property("hasMapsKey", mapsKey.map { it.isNotBlank() })
    val output = layout.buildDirectory.dir("generated/appConfig/kotlin")
    outputs.dir(output)
    doLast {
        // A release (Google Play, the website) never signs in without Google, and dev sign-in only goes with a local server.
        check(!devSignIn.get() || !release) { "kapelusz.devSignIn is set (local.properties or KAPELUSZ_DEV_SIGN_IN): no release with it" }
        check(!devSignIn.get() || Regex("http://(10\\.0\\.2\\.2|localhost|127\\.0\\.0\\.1)(:\\d+)?/?").matches(apiUrl.get())) {
            "kapelusz.devSignIn is only for a local API (LOCAL_DEVELOPMENT.md), not ${apiUrl.get()}"
        }
        val file = output.get().file("com/jacekgajek/kapelusz/app/AppConfig.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |package com.jacekgajek.kapelusz.app
            |
            |/** Generated by the generateAppConfig Gradle task. */
            |object AppConfig {
            |    const val API_URL = "${apiUrl.get().trimEnd('/')}"
            |    const val GOOGLE_WEB_CLIENT_ID = "${webClientId.get()}"
            |    const val WEB_URL = "${webUrl.get().trimEnd('/')}"
            |    const val VERSION_NAME = "${versionName.get()}"
            |    const val VERSION_CODE = ${versionCode.get().toInt()}
            |
            |    /** Whether the Android app has a Google Maps key, so a place can be picked on a map. */
            |    const val HAS_MAPS_KEY = ${mapsKey.get().isNotBlank()}
            |
            |    /** Sign-in as a made-up user instead of Google's, for the local server (LOCAL_DEVELOPMENT.md). */
            |    const val DEV_SIGN_IN = ${devSignIn.get()}
            |
            |    /** Shown in a corner of the app, e.g. "0.5.0 (7)"; local builds say "dev". */
            |    val VERSION_LABEL: String get() = if (VERSION_CODE > 0) "${'$'}VERSION_NAME (${'$'}VERSION_CODE)" else "${'$'}VERSION_NAME (dev)"
            |}
            |
            """.trimMargin(),
        )
    }
}

/**
 * The local server (localServer/) for the end-to-end tests: one process per build, in memory, started by the first test
 * task that needs it and stopped when the build ends. Its output goes to [Params.log].
 */
abstract class LocalServerService :
    BuildService<LocalServerService.Params>,
    AutoCloseable {
    interface Params : BuildServiceParameters {
        val java: RegularFileProperty
        val classpath: ConfigurableFileCollection
        val port: Property<Int>
        val log: RegularFileProperty
    }

    private var process: Process? = null

    @Synchronized
    fun start() {
        if (process != null) return
        val log = parameters.log.get().asFile.apply { parentFile.mkdirs() }
        val port = parameters.port.get()
        val started = ProcessBuilder(
            parameters.java.get().asFile.path,
            "-cp",
            parameters.classpath.asPath,
            "com.jacekgajek.kapelusz.local.LocalServerKt",
            "--memory",
        ).redirectErrorStream(true).redirectOutput(log).apply {
            environment()["KAPELUSZ_LOCAL_PORT"] = port.toString()
            environment()["WEB_URL"] = "http://localhost:$port"
        }.start()
        process = started
        val deadline = System.currentTimeMillis() + 60_000
        while (!listening(port)) {
            check(started.isAlive) { "The local server stopped: ${log.readText().takeLast(2000)}" }
            check(System.currentTimeMillis() < deadline) { "The local server did not listen on $port within a minute: ${log.readText().takeLast(2000)}" }
            Thread.sleep(200)
        }
    }

    private fun listening(port: Int) = runCatching { Socket("localhost", port).close() }.isSuccess

    override fun close() {
        process?.let {
            it.destroy()
            it.waitFor(10, TimeUnit.SECONDS)
        }
        process = null
    }
}

/** Starts the local server before a task's work; a class of its own, which the configuration cache can store. */
class StartLocalServer(private val service: Provider<LocalServerService>) : Action<Task> {
    override fun execute(task: Task) = service.get().start()
}

